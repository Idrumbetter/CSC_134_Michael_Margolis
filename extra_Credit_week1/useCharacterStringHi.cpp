// include the iostream library for input and output
#include <iostream>

//use the standard namespace to avoid having to use std:: before every standard library function
using namespace std;

int main()
{
    // assigning the character class to letter
    char letter;

    // assigning H to letter and printing
    letter = 'H';
    cout << letter;
    
    //re-assigning i to letter and printing
    letter = 'i';
    cout << letter;
    
    // re-assigning ! to letter and printing
    letter = '!';
    cout << letter;

    return 0;
}